// wordmark draws s in the pixel font, three rows high with half blocks.
// Each pixel is scale cells wide. It gives the rows and their width in
// cells.
func wordmark(s string, scale int) ([3]string, int) {
	var px [6][]bool
	for _, r := range strings.ToLower(s) {
		g, ok := font[r]
		if !ok {
			g = [5]string{"...", "...", "...", "...", "..."}
		}
		for y := range 6 {
			for x := range 4 {
				on := y < 5 && x < 3 && g[y][x] == '#'
				for range scale {
					px[y] = append(px[y], on)
				}
			}
		}
	}
	var rows [3]string
	for r := range 3 {
		var sb strings.Builder
		for x := range px[0] {
			top, bot := px[2*r][x], px[2*r+1][x]
			switch {
			case top && bot:
				sb.WriteString("█")
			case top:
				sb.WriteString("▀")
			case bot:
				sb.WriteString("▄")
			default:
				sb.WriteString(" ")
			}
		}
		rows[r] = sb.String()
	}
	return rows, len(px[0])
}
