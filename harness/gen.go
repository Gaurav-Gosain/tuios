//go:build ignore

// gen.go packs manifests/*.toml into manifests.tar.gz, the archive the harness
// package embeds, and writes names_gen.go, every bundled harness id and alias
// as static data, so a name resolves without reading the archive. Run it after
// editing a bundled manifest:
//
//	go generate ./harness
//
// The archive is deterministic: names in order, no times, no owners, so the
// same files give the same bytes on the same Go version.
// TestBundledArchiveMatchesFiles fails when the archive or the name table and
// the files differ.
package main

import (
	"archive/tar"
	"bytes"
	"cmp"
	"compress/gzip"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/pelletier/go-toml/v2"
)

func main() {
	paths, err := filepath.Glob(filepath.Join("manifests", "*.toml"))
	if err != nil {
		log.Fatal(err)
	}
	slices.Sort(paths)

	var buf bytes.Buffer
	zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	if err != nil {
		log.Fatal(err)
	}
	tw := tar.NewWriter(zw)
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			log.Fatal(err)
		}
		hdr := &tar.Header{
			Typeflag: tar.TypeReg,
			Name:     filepath.Base(p),
			Mode:     0o644,
			Size:     int64(len(data)),
			Format:   tar.FormatUSTAR,
		}
		if err := tw.WriteHeader(hdr); err != nil {
			log.Fatal(err)
		}
		if _, err := tw.Write(data); err != nil {
			log.Fatal(err)
		}
	}
	if err := tw.Close(); err != nil {
		log.Fatal(err)
	}
	if err := zw.Close(); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("manifests.tar.gz", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	writeNames(paths)
}

// writeNames writes names_gen.go: each id names itself, then each alias names
// its manifest unless an id or an earlier alias already took it. Sorted by
// name for a binary search. TestBundledArchiveMatchesFiles holds the same rule.
func writeNames(paths []string) {
	type entry struct{ name, id string }
	var ids, aliases []entry
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			log.Fatal(err)
		}
		var m struct {
			ID      string   `toml:"id"`
			Aliases []string `toml:"aliases"`
		}
		if err := toml.Unmarshal(data, &m); err != nil {
			log.Fatalf("%s: %v", p, err)
		}
		id := strings.TrimSpace(m.ID)
		ids = append(ids, entry{id, id})
		for _, a := range m.Aliases {
			if a = strings.ToLower(strings.TrimSpace(a)); a != "" && a != id {
				aliases = append(aliases, entry{a, id})
			}
		}
	}
	taken := map[string]bool{}
	var table []entry
	for _, e := range append(ids, aliases...) {
		if !taken[e.name] {
			taken[e.name] = true
			table = append(table, e)
		}
	}
	slices.SortFunc(table, func(a, b entry) int { return cmp.Compare(a.name, b.name) })

	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go; DO NOT EDIT.\n\npackage harness\n\n")
	b.WriteString("// bundledNameTable is every bundled manifest's id and alias, sorted by name,\n")
	b.WriteString("// each with the id it names. See BundledCanonical.\n")
	b.WriteString("var bundledNameTable = [...]struct{ name, id string }{\n")
	for _, e := range table {
		fmt.Fprintf(&b, "\t{%q, %q},\n", e.name, e.id)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("names_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
