package main

import (
	"flag"
	"os"
	"runtime"
	"strings"
	"testing"

	"github.com/Gaurav-Gosain/tuios/internal/config"
)

var updateDocs = flag.Bool("update", false, "write docs/keybindings-defaults.md again from the default keymaps")

const keybindingDefaultsDoc = "../../docs/keybindings-defaults.md"

// TestKeybindingDefaultsDocMatchesKeymaps holds docs/keybindings-defaults.md
// to the default keymaps: the rows tuios keybinds list prints for a config
// that changes nothing. The page is generated, so an action or a default key
// added, moved or removed fails here until the page is written again with
// -update.
//
// Some default keys differ on macOS, so the page is the Linux one and the
// test runs on Linux only.
func TestKeybindingDefaultsDocMatchesKeymaps(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("the page shows the Linux keys")
	}
	want := renderKeybindingDefaultsDoc()
	if *updateDocs {
		if err := os.WriteFile(keybindingDefaultsDoc, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(keybindingDefaultsDoc)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("docs/keybindings-defaults.md does not match the default keymaps. Run: go test ./cmd/tuios -run TestKeybindingDefaultsDocMatchesKeymaps -update")
	}
}

// renderKeybindingDefaultsDoc writes the tables of tuios keybinds list for
// the default config as Markdown.
func renderKeybindingDefaultsDoc() string {
	var b strings.Builder
	w := func(parts ...string) {
		for _, p := range parts {
			b.WriteString(p)
		}
	}
	w("# Default keys\n\n",
		"Do not edit this file by hand. A test writes it from the default keymaps, the same rows that `tuios keybinds list` prints for a config that changes no key.\n",
		"To write it again, run `go test ./cmd/tuios -run TestKeybindingDefaultsDocMatchesKeymaps -update`.\n\n",
		"[KEYBINDINGS.md](KEYBINDINGS.md) tells how the keys work and how to change them.\n",
		"The keys are the ones on Linux. Some keys are different on macOS.\n",
		"Run `tuios keybinds list` to see the keys that your config sets.\n")
	for _, g := range groupKeybindRows(keybindRows(config.DefaultConfig())) {
		w("\n## ", mdCell(g.title), "\n\n| Keys | Action | Description |\n|---|---|---|\n")
		for _, r := range g.rows {
			keys := make([]string, len(r.Keys))
			for i, k := range r.Keys {
				keys[i] = "`" + mdCell(k) + "`"
			}
			action := ""
			if r.Action != "" {
				action = "`" + r.Action + "`"
			}
			w("| ", strings.Join(keys, ", "), " | ", action, " | ", mdCell(r.Description), " |\n")
		}
	}
	return b.String()
}

// mdCell makes s safe inside a Markdown table cell.
func mdCell(s string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(s), " "), "|", "\\|")
}
