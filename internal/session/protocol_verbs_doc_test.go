package session

import (
	"flag"
	"os"
	"regexp"
	"strings"
	"testing"
)

var updateDocs = flag.Bool("update", false, "write docs/protocol-verbs.md again from the verb registry")

const protocolVerbsDoc = "../../docs/protocol-verbs.md"

// TestProtocolVerbsDocMatchesRegistry holds docs/protocol-verbs.md to the verb
// registry, the table list-verbs reads. The page is generated, so a verb, a
// param or a result field added, renamed or removed in the code fails here
// until the page is written again with -update.
func TestProtocolVerbsDocMatchesRegistry(t *testing.T) {
	want := renderProtocolVerbsDoc()
	if *updateDocs {
		if err := os.WriteFile(protocolVerbsDoc, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(protocolVerbsDoc)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("docs/protocol-verbs.md does not match the verb registry. Run: go test ./internal/session -run TestProtocolVerbsDocMatchesRegistry -update")
	}
}

// TestProtocolHeadingsNameRealVerbs fails on a heading in the Verbs part of
// docs/protocol.md that names a verb the registry does not have, such as a
// verb that was renamed or removed. A heading counts as a verb heading when
// every item it lists is a lower-case name, such as "### split-window,
// zoom-window" or "### ship-push and ship-pr".
func TestProtocolHeadingsNameRealVerbs(t *testing.T) {
	data, err := os.ReadFile("../../docs/protocol.md")
	if err != nil {
		t.Fatal(err)
	}
	_, verbs, ok := strings.Cut(string(data), "\n## Verbs\n")
	if !ok {
		t.Fatal("protocol.md has no Verbs section")
	}
	name := regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)
	reg := verbRegistry()
	checked := 0
	fenced := false
	for line := range strings.SplitSeq(verbs, "\n") {
		if strings.HasPrefix(line, "```") {
			fenced = !fenced
		}
		if fenced || !strings.HasPrefix(line, "### ") {
			continue
		}
		text := strings.ReplaceAll(strings.TrimPrefix(line, "### "), "`", "")
		items := strings.FieldsFunc(strings.ReplaceAll(text, " and ", ","), func(r rune) bool { return r == ',' })
		verbHeading := len(items) > 0
		for i := range items {
			items[i] = strings.TrimSpace(items[i])
			verbHeading = verbHeading && name.MatchString(items[i])
		}
		if !verbHeading {
			continue
		}
		for _, v := range items {
			checked++
			if _, ok := reg[v]; !ok {
				t.Errorf("protocol.md has a section for %q, which is not a verb: %s", v, line)
			}
		}
	}
	if checked < 50 {
		t.Fatalf("found %d verb headings in protocol.md, want the catalog", checked)
	}
}

// renderProtocolVerbsDoc writes the verb reference from the registry, one
// section per verb in the order list-verbs uses.
func renderProtocolVerbsDoc() string {
	var b strings.Builder
	w := func(parts ...string) {
		for _, p := range parts {
			b.WriteString(p)
		}
	}
	b.WriteString("# Verb reference\n\n")
	b.WriteString("Do not edit this file by hand. A test writes it from the verb registry, the same table that `tuios list-verbs` prints.\n")
	b.WriteString("To write it again, run `go test ./internal/session -run TestProtocolVerbsDocMatchesRegistry -update`.\n\n")
	b.WriteString("[protocol.md](protocol.md) tells how to call a verb and what the errors mean.\n")
	b.WriteString("It also has more about the verbs that need it.\n\n")
	names := knownVerbNames()
	b.WriteString("## Verbs\n\n")
	for _, n := range names {
		w("- [`", n, "`](#", n, ")\n")
	}
	for _, n := range names {
		d := describeVerb(n, verbRegistry()[n])
		w("\n### `", n, "`\n\n")
		w(oneLine(d.Description), "\n")
		if st := d.Stream; st != nil {
			if st.Param == "" {
				b.WriteString("\nThe connection stays open after the reply.\n")
			} else {
				w("\nThe connection stays open after the reply when `", st.Param, "` is ", codeList(st.Values, "or"), ".\n")
			}
		}
		if len(d.Params) == 0 {
			b.WriteString("\nNo params.\n")
		} else {
			b.WriteString("\n| Param | Type | Required | Default | Description |\n|---|---|---|---|---|\n")
			for _, p := range d.Params {
				req := ""
				if p.Required {
					req = "yes"
				}
				def := ""
				if p.Default != "" {
					def = "`" + cell(p.Default) + "`"
				}
				w("| `", p.Name, "` | ", cell(p.Type), " | ", req, " | ", def, " | ", paramText(p), " |\n")
			}
		}
		if len(d.Returns) > 0 {
			b.WriteString("\n| Result field | Type | Description |\n|---|---|---|\n")
			for _, p := range d.Returns {
				typ := cell(p.Type)
				if p.Nullable {
					typ += " or null"
				}
				w("| `", p.Name, "` | ", typ, " | ", paramText(p), " |\n")
			}
		}
		for _, ex := range d.Examples {
			w("\n```json\n", ex, "\n```\n")
		}
	}
	return b.String()
}

// paramText is a param's description with its accepted values after it.
func paramText(p verbParam) string {
	s := cell(p.Description)
	if len(p.Accepted) > 0 {
		var vals []string
		for _, v := range p.Accepted {
			if v == "" {
				v = "(empty)"
			}
			vals = append(vals, v)
		}
		s = strings.TrimSpace(s + " One of " + codeList(vals, "or") + ".")
	}
	return s
}

// codeList writes values as code spans: `a`, `b` or `c`.
func codeList(vals []string, last string) string {
	quoted := make([]string, len(vals))
	for i, v := range vals {
		quoted[i] = "`" + cell(v) + "`"
	}
	if len(quoted) < 2 {
		return strings.Join(quoted, "")
	}
	return strings.Join(quoted[:len(quoted)-1], ", ") + " " + last + " " + quoted[len(quoted)-1]
}

// oneLine joins a description onto one line.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell makes s safe inside a table cell.
func cell(s string) string { return strings.ReplaceAll(oneLine(s), "|", "\\|") }
